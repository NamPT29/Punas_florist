-- Trừ kho theo công thức các sản phẩm trong đơn (gọi khi bắt đầu cắm).
create or replace function _deduct_order_stock(p_order bigint) returns void
language plpgsql set search_path = public as $$
declare r record;
begin
  -- Gọi lại nhiều lần cũng chỉ trừ một lần.
  perform 1 from orders where id = p_order and not stock_deducted and status <> 'huy' for update;
  if not found then return; end if;
  for r in
    select c.material_id, sum(c.qty * i.qty) as qty, m.cost
    from order_items i
    join product_components c on c.product_id = i.product_id
    join materials m on m.id = c.material_id
    where i.order_id = p_order
    group by c.material_id, m.cost
  loop
    update materials set stock = stock - r.qty where id = r.material_id;
    insert into stock_moves (material_id, kind, qty, unit_cost, order_id, note)
    values (r.material_id, 'xuat', -r.qty, r.cost, p_order, 'Đơn #' || p_order);
  end loop;
  update orders set stock_deducted = true where id = p_order;
end $$;

-- Hoàn lại đúng lượng đã trừ cho đơn (kể cả khi công thức đã đổi sau đó).
create or replace function _restore_order_stock(p_order bigint) returns void
language plpgsql set search_path = public as $$
declare r record;
begin
  perform 1 from orders where id = p_order and stock_deducted for update;
  if not found then return; end if;
  for r in
    select material_id, -sum(qty) as qty from stock_moves
    where order_id = p_order group by material_id having sum(qty) < 0
  loop
    update materials set stock = stock + r.qty where id = r.material_id;
    insert into stock_moves (material_id, kind, qty, order_id, note)
    values (r.material_id, 'hoan', r.qty, p_order, 'Hủy đơn #' || p_order);
  end loop;
  update orders set stock_deducted = false where id = p_order;
end $$;

create or replace function set_order_status(p_order bigint, p_status text) returns void
language plpgsql set search_path = public as $$
declare
  o orders%rowtype;
  flow text[] := array['moi', 'dang_cam', 'dang_giao', 'da_giao'];
begin
  select * into o from orders where id = p_order for update;
  if not found then raise exception 'Không tìm thấy đơn #%', p_order; end if;
  if o.status in ('da_giao', 'huy') then
    raise exception 'Đơn #% đã kết thúc, không đổi trạng thái được', p_order;
  end if;
  if p_status = 'huy' then
    if o.stock_deducted then perform _restore_order_stock(p_order); end if;
  elsif array_position(flow, p_status) is null then
    raise exception 'Trạng thái không hợp lệ: %', p_status;
  elsif array_position(flow, p_status) <= array_position(flow, o.status) then
    raise exception 'Không thể quay lại trạng thái trước';
  elsif not o.stock_deducted then
    perform _deduct_order_stock(p_order);
  end if;
  update orders set status = p_status where id = p_order;
end $$;

-- Tạo đơn: tự tạo/nhận khách theo SĐT, chốt giá (giá lễ nếu đúng ngày lễ).
-- items: [{product_id, qty}] hoặc sản phẩm tùy chọn [{name, price, qty}].
create or replace function create_order(p jsonb) returns bigint
language plpgsql set search_path = public as $$
declare
  v_phone text := regexp_replace(coalesce(p->>'customer_phone', ''), '\D', '', 'g');
  v_name text := trim(coalesce(p->>'customer_name', ''));
  v_date date := (p->>'delivery_date')::date;
  v_customer bigint;
  v_order bigint;
  v_holiday boolean;
  v_item jsonb;
  v_product products%rowtype;
  v_price numeric;
  v_qty int;
  v_subtotal numeric := 0;
begin
  if length(v_phone) < 9 then raise exception 'Số điện thoại không hợp lệ'; end if;
  if v_name = '' then raise exception 'Chưa nhập tên khách'; end if;
  if v_date is null then raise exception 'Chưa chọn ngày giao'; end if;
  if jsonb_array_length(coalesce(p->'items', '[]'::jsonb)) = 0 then
    raise exception 'Đơn hàng chưa có sản phẩm';
  end if;

  select to_char(v_date, 'MM-DD') = any(holidays) into v_holiday from settings where id = 1;

  insert into customers (name, phone, address)
  values (v_name, v_phone, case when coalesce((p->>'pickup')::boolean, false) then '' else coalesce(p->>'address', '') end)
  on conflict (phone) do update set name = excluded.name
  returning id into v_customer;

  insert into orders (customer_id, recipient_name, recipient_phone, address, pickup, anonymous,
                      delivery_date, delivery_slot, card_message, note, ship_fee, discount,
                      paid, payment_method)
  values (v_customer,
          coalesce(nullif(trim(p->>'recipient_name'), ''), v_name),
          coalesce(nullif(regexp_replace(coalesce(p->>'recipient_phone', ''), '\D', '', 'g'), ''), v_phone),
          coalesce(p->>'address', ''),
          coalesce((p->>'pickup')::boolean, false),
          coalesce((p->>'anonymous')::boolean, false),
          v_date,
          coalesce(p->>'delivery_slot', ''),
          coalesce(p->>'card_message', ''),
          coalesce(p->>'note', ''),
          greatest(coalesce((p->>'ship_fee')::numeric, 0), 0),
          greatest(coalesce((p->>'discount')::numeric, 0), 0),
          coalesce((p->>'paid')::boolean, false),
          coalesce(nullif(p->>'payment_method', ''), 'tien_mat'))
  returning id into v_order;

  for v_item in select * from jsonb_array_elements(p->'items') loop
    v_qty := coalesce((v_item->>'qty')::int, 1);
    if v_qty < 1 then raise exception 'Số lượng không hợp lệ'; end if;
    if v_item->>'product_id' is not null then
      select * into v_product from products where id = (v_item->>'product_id')::bigint;
      if not found then raise exception 'Không tìm thấy sản phẩm'; end if;
      if not v_product.active then raise exception 'Sản phẩm "%" đã ngừng bán', v_product.name; end if;
      v_price := case when v_holiday and v_product.holiday_price is not null
                      then v_product.holiday_price else v_product.price end;
      insert into order_items (order_id, product_id, name, price, qty)
      values (v_order, v_product.id, v_product.name, v_price, v_qty);
    else
      v_price := (v_item->>'price')::numeric;
      if v_price is null or v_price < 0 or coalesce(trim(v_item->>'name'), '') = '' then
        raise exception 'Sản phẩm tùy chọn cần có tên và giá';
      end if;
      insert into order_items (order_id, product_id, name, price, qty)
      values (v_order, null, trim(v_item->>'name'), v_price, v_qty);
    end if;
    v_subtotal := v_subtotal + v_price * v_qty;
  end loop;

  update orders set subtotal = v_subtotal, total = greatest(v_subtotal + ship_fee - discount, 0)
  where id = v_order;

  -- Bán tại quầy: tạo xong là giao luôn.
  if coalesce(p->>'status', 'moi') <> 'moi' then
    perform set_order_status(v_order, p->>'status');
  end if;
  return v_order;
end $$;

-- Nhập hoa: tăng tồn, cập nhật giá nhập, tự ghi khoản chi "Nhập hoa".
create or replace function import_stock(p_material bigint, p_qty numeric, p_unit_cost numeric,
                                        p_note text default '', p_date date default current_date)
returns void language plpgsql set search_path = public as $$
declare m materials%rowtype;
begin
  if p_qty is null or p_qty <= 0 then raise exception 'Số lượng nhập phải lớn hơn 0'; end if;
  if p_unit_cost is null or p_unit_cost < 0 then raise exception 'Giá nhập không hợp lệ'; end if;
  select * into m from materials where id = p_material for update;
  if not found then raise exception 'Không tìm thấy hoa trong kho'; end if;
  update materials set stock = stock + p_qty, cost = p_unit_cost, last_import = p_date where id = p_material;
  insert into stock_moves (material_id, kind, qty, unit_cost, note)
  values (p_material, 'nhap', p_qty, p_unit_cost, coalesce(p_note, ''));
  if p_qty * p_unit_cost > 0 then
    insert into expenses (date, category, amount, note)
    values (p_date, 'Nhập hoa', p_qty * p_unit_cost,
            trim(m.name || ' × ' || trim_scale(p_qty) || ' ' || m.unit || ' ' || coalesce(p_note, '')));
  end if;
end $$;

-- Hủy hoa héo / dập.
create or replace function waste_stock(p_material bigint, p_qty numeric, p_note text default '')
returns void language plpgsql set search_path = public as $$
declare m materials%rowtype;
begin
  if p_qty is null or p_qty <= 0 then raise exception 'Số lượng hủy phải lớn hơn 0'; end if;
  select * into m from materials where id = p_material for update;
  if not found then raise exception 'Không tìm thấy hoa trong kho'; end if;
  if p_qty > m.stock then raise exception 'Số lượng hủy lớn hơn tồn kho (% %)', trim_scale(m.stock), m.unit; end if;
  update materials set stock = stock - p_qty where id = p_material;
  insert into stock_moves (material_id, kind, qty, unit_cost, note)
  values (p_material, 'huy', -p_qty, m.cost, coalesce(p_note, ''));
end $$;

-- Kiểm kho: đặt tồn kho bằng số đếm thực tế.
create or replace function adjust_stock(p_material bigint, p_actual numeric, p_note text default '')
returns void language plpgsql set search_path = public as $$
declare m materials%rowtype;
begin
  if p_actual is null or p_actual < 0 then raise exception 'Số lượng thực tế không hợp lệ'; end if;
  select * into m from materials where id = p_material for update;
  if not found then raise exception 'Không tìm thấy hoa trong kho'; end if;
  if p_actual <> m.stock then
    update materials set stock = p_actual where id = p_material;
    insert into stock_moves (material_id, kind, qty, unit_cost, note)
    values (p_material, 'kiem', p_actual - m.stock, m.cost, coalesce(nullif(p_note, ''), 'Kiểm kho'));
  end if;
end $$;

-- Lưu sản phẩm cùng công thức. p: {id?, name, categories, price, holiday_price, photo_url, active, components:[{material_id, qty}]}
create or replace function save_product(p jsonb) returns bigint
language plpgsql set search_path = public as $$
declare v_id bigint := (p->>'id')::bigint;
begin
  if coalesce(trim(p->>'name'), '') = '' then raise exception 'Chưa nhập tên sản phẩm'; end if;
  if v_id is null then
    insert into products (name, description, categories, price, holiday_price, photo_url, active)
    values (trim(p->>'name'), coalesce(trim(p->>'description'), ''),
            coalesce(array(select jsonb_array_elements_text(p->'categories')), '{}'),
            (p->>'price')::numeric, (p->>'holiday_price')::numeric, p->>'photo_url',
            coalesce((p->>'active')::boolean, true))
    returning id into v_id;
  else
    update products set name = trim(p->>'name'), description = coalesce(trim(p->>'description'), ''),
      categories = coalesce(array(select jsonb_array_elements_text(p->'categories')), '{}'),
      price = (p->>'price')::numeric, holiday_price = (p->>'holiday_price')::numeric,
      photo_url = p->>'photo_url', active = coalesce((p->>'active')::boolean, true)
    where id = v_id;
    if not found then raise exception 'Không tìm thấy sản phẩm'; end if;
  end if;
  delete from product_components where product_id = v_id;
  insert into product_components (product_id, material_id, qty)
  select v_id, (c->>'material_id')::bigint, sum((c->>'qty')::numeric)
  from jsonb_array_elements(coalesce(p->'components', '[]'::jsonb)) c
  group by (c->>'material_id')::bigint;
  return v_id;
end $$;

-- Trang cho khách (không cần đăng nhập): chỉ trả thông tin shop và sản phẩm đang bán,
-- không có giá vốn, công thức, tồn kho.
create or replace function public_catalog() returns jsonb
language sql stable security definer set search_path = public as $$
  select jsonb_build_object(
    'shop', (select jsonb_build_object('shop_name', shop_name, 'phone', phone, 'zalo', zalo, 'address', address,
                                       'intro', intro, 'open_hours', open_hours, 'holidays', holidays)
             from settings where id = 1),
    'products', coalesce((select jsonb_agg(jsonb_build_object(
                  'id', id, 'name', name, 'description', description, 'categories', categories,
                  'price', price, 'holiday_price', holiday_price, 'photo_url', photo_url) order by name)
                from products where active), '[]'::jsonb));
$$;
revoke all on function public_catalog() from public;
grant execute on function public_catalog() to anon, authenticated;

