-- ---------- Nhân viên được phép dùng app ----------
create table if not exists staff (
  user_id uuid primary key references auth.users(id) on delete cascade,
  name text not null default '',
  role text not null default 'staff' check (role in ('owner', 'staff')),
  created_at timestamptz not null default now()
);

create or replace function is_staff() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from staff where user_id = auth.uid());
$$;

create or replace function is_owner() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from staff where user_id = auth.uid() and role = 'owner');
$$;

-- ---------- Cài đặt shop (chỉ 1 dòng) ----------
create table if not exists settings (
  id int primary key default 1 check (id = 1),
  shop_name text not null default 'Tiệm hoa',
  phone text not null default '',
  address text not null default '',
  default_ship_fee numeric not null default 30000 check (default_ship_fee >= 0),
  -- Ngày lễ dạng 'MM-DD': sản phẩm có giá lễ sẽ tự dùng giá lễ vào các ngày này.
  holidays text[] not null default array['02-14', '03-08', '10-20', '11-20', '12-24']
);
insert into settings (id) values (1) on conflict do nothing;
-- Thông tin hiện trên trang cho khách.
alter table settings add column if not exists zalo text not null default '';
alter table settings add column if not exists intro text not null default '';
alter table settings add column if not exists open_hours text not null default '';

-- ---------- Kho: hoa và phụ liệu ----------
create table if not exists materials (
  id bigint generated by default as identity primary key,
  name text not null unique,
  kind text not null default 'hoa' check (kind in ('hoa', 'phu_lieu')),
  unit text not null default 'cành',
  stock numeric not null default 0,
  cost numeric not null default 0 check (cost >= 0),
  min_stock numeric not null default 0 check (min_stock >= 0),
  shelf_life_days int not null default 5 check (shelf_life_days > 0),
  last_import date,
  active boolean not null default true
);

-- ---------- Sản phẩm (mẫu bó hoa) và công thức ----------
create table if not exists products (
  id bigint generated by default as identity primary key,
  name text not null,
  categories text[] not null default '{}',
  price numeric not null check (price >= 0),
  holiday_price numeric check (holiday_price >= 0),
  photo_url text,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

-- Mô tả hiện trên trang cho khách.
alter table products add column if not exists description text not null default '';

create table if not exists product_components (
  product_id bigint not null references products(id) on delete cascade,
  material_id bigint not null references materials(id) on delete restrict,
  qty numeric not null check (qty > 0),
  primary key (product_id, material_id)
);

-- ---------- Khách hàng ----------
create table if not exists customers (
  id bigint generated by default as identity primary key,
  name text not null,
  phone text not null unique,
  address text not null default '',
  birthday date,
  note text not null default '',
  created_at timestamptz not null default now()
);

-- ---------- Đơn hàng ----------
create table if not exists orders (
  id bigint generated by default as identity primary key,
  customer_id bigint not null references customers(id),
  recipient_name text not null default '',
  recipient_phone text not null default '',
  address text not null default '',
  pickup boolean not null default false,
  anonymous boolean not null default false,
  delivery_date date not null,
  delivery_slot text not null default '',
  card_message text not null default '',
  note text not null default '',
  subtotal numeric not null default 0,
  ship_fee numeric not null default 0 check (ship_fee >= 0),
  discount numeric not null default 0 check (discount >= 0),
  total numeric not null default 0,
  status text not null default 'moi'
    check (status in ('moi', 'dang_cam', 'dang_giao', 'da_giao', 'huy')),
  -- true khi đã trừ kho (lúc bắt đầu cắm). Hủy đơn sẽ hoàn lại kho.
  stock_deducted boolean not null default false,
  paid boolean not null default false,
  payment_method text not null default 'tien_mat'
    check (payment_method in ('tien_mat', 'chuyen_khoan', 'the', 'vi')),
  shipper text not null default '',
  photo_url text,
  created_at timestamptz not null default now(),
  created_by uuid default auth.uid()
);
create index if not exists orders_delivery_date_idx on orders (delivery_date);
create index if not exists orders_status_idx on orders (status);
create index if not exists orders_customer_idx on orders (customer_id);

create table if not exists order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references orders(id) on delete cascade,
  product_id bigint references products(id) on delete set null,
  name text not null,
  price numeric not null check (price >= 0),
  qty int not null check (qty > 0)
);
create index if not exists order_items_order_idx on order_items (order_id);

-- ---------- Lịch sử kho ----------
create table if not exists stock_moves (
  id bigint generated by default as identity primary key,
  material_id bigint not null references materials(id) on delete cascade,
  kind text not null check (kind in ('nhap', 'xuat', 'huy', 'hoan', 'kiem')),
  qty numeric not null,              -- dương: vào kho, âm: ra kho
  unit_cost numeric not null default 0,
  order_id bigint references orders(id) on delete set null,
  note text not null default '',
  created_at timestamptz not null default now()
);
create index if not exists stock_moves_material_idx on stock_moves (material_id, created_at desc);

-- ---------- Thu chi ----------
create table if not exists expenses (
  id bigint generated by default as identity primary key,
  date date not null,
  category text not null,
  amount numeric not null check (amount > 0),
  note text not null default '',
  created_at timestamptz not null default now()
);
create index if not exists expenses_date_idx on expenses (date);

-- ---------- Thống kê khách hàng ----------
create or replace view customer_stats with (security_invoker = true) as
select c.*,
  count(o.id) filter (where o.status <> 'huy') as order_count,
  coalesce(sum(o.total) filter (where o.status <> 'huy'), 0) as total_spent,
  coalesce(sum(o.total) filter (where o.status <> 'huy' and not o.paid), 0) as debt,
  max(o.delivery_date) filter (where o.status <> 'huy') as last_order_date
from customers c
left join orders o on o.customer_id = c.id
group by c.id;

